// ==========================================================
// routes/storage.js
// STORAGE ROUTES
// ==========================================================

const express =
    require("express");

const router =
    express.Router();


// ==========================================================
// STORAGE CONTROLLER
// ==========================================================

const storageController =
    require("../controllers/storage/storageController");


// ==========================================================
// ADD STORAGE FORM
// ==========================================================

router.get(
    "/:id/add",
    storageController.form
);


// ==========================================================
// CREATE STORAGE
// ==========================================================

router.post(
    "/:id/add",
    storageController.create
);


// ==========================================================
// STORAGE PAGE
// ==========================================================

router.get(
    "/:id",
    storageController.list
);


// ==========================================================
// EXPORT
// ==========================================================

module.exports =
    router;