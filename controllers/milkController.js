// ==========================================================
// controllers/milkController.js
// ==========================================================
//
// PURPOSE
// ----------------------------------------------------------
// General controller for the milk module.
//
// Handles:
//
// • Milk statistics
// • Daily statistics
// • Milk sales
// • Standing orders
// • Milk pricing
// • Milking history
// • Milking status
//
// DOES NOT HANDLE:
//
// • GET  /milk
// • POST /milk
// • GET  /milk/edit/:id
// • POST /milk/:id
//
// Those belong exclusively to:
//
//     controllers/milkCollectController.js
//
// IMPORTANT FARM PRODUCTION RULE
// ----------------------------------------------------------
//
// Farm production and milk sales are FARM-SCOPED.
//
// The controller passes the authenticated user and selected
// farm to the service.
//
// The controller does NOT calculate:
//
//     • farm production
//     • farm available milk
//     • farm sales
//     • farm revenue
//
// Those calculations belong to milkService.js.
//
// ==========================================================


const mongoose =
    require("mongoose");


const milkService =
    require("../services/milkService");


// ==========================================================
// AUTHENTICATED USER
// ==========================================================
//
// Application normally uses:
//
//     req.session.user
//
// Some middleware may expose:
//
//     req.user
//
// Support both.
//
// ==========================================================

function getUser(
    req
) {

    return (
        req.session?.user ||
        req.user ||
        null
    );

}


// ==========================================================
// ADMIN CHECK
// ==========================================================

function isAdmin(
    req
) {

    const user =
        getUser(req);


    return Boolean(
        user &&
        user.role === "admin"
    );

}


// ==========================================================
// OBJECT ID VALIDATION
// ==========================================================

function isValidObjectId(
    value
) {

    return mongoose.Types.ObjectId.isValid(
        value
    );

}


// ==========================================================
// ERROR RESPONSE
// ==========================================================

function sendError(
    res,
    error,
    fallback
) {

    console.error(
        error
    );


    // ======================================================
    // BUSINESS ERRORS
    // ======================================================
    //
    // These are errors intentionally generated by
    // milkService.js.
    //
    // They are client/business-rule failures and should
    // not become generic HTTP 500 responses.
    //
    // ======================================================

    const businessErrors = [

        "MILK_USER_REQUIRED",

        "MILK_ADMIN_REQUIRED",

        "MILK_FARM_REQUIRED",

        "MILK_FARM_ACCESS_DENIED",

        "MILK_INVALID_ANIMAL",

        "MILK_NO_RECORDS",

        "MILK_TIME_CLOSED",

        "MILK_INVALID_QUANTITY",

        "MILK_DUPLICATE_RECORD",

        "MILK_ALREADY_RECORDED",

        "MILK_SAVE_FAILED",

        "MILK_NOT_FOUND",

        "MILK_INVALID_DAY",

        "MILK_INVALID_MONTH",

        "MILK_INVALID_PRICE",

        "MILK_INVALID_CUSTOMER",

        "MILK_INSUFFICIENT",

        "MILK_DAY_LOCKED",

        "MILK_INVALID_ORDER",

        "MILK_ORDER_NOT_FOUND",

        "MILK_ORDER_INACTIVE",

        "MILK_ORDER_NOT_ACTIVE",

        "MILK_ORDER_ALREADY_PROCESSED",

        "MILK_SUMMARY_NOT_FOUND"

    ];


    if (
        error?.code &&
        businessErrors.includes(
            error.code
        )
    ) {

        return res
            .status(400)
            .send(
                error.message ||
                fallback ||
                "Unable to complete the request."
            );

    }


    return res
        .status(500)
        .send(
            error?.message ||
            fallback ||
            "An error occurred."
        );

}


// ==========================================================
// GET MILK STATISTICS
// ==========================================================
//
// GET /stats
//
// Supported:
//
// /stats
//
// /stats?type=day&date=2026-08-13
//
// /stats?type=month&month=2026-08
//
// ==========================================================

exports.getMilkStats =
async function(
    req,
    res
) {

    try {

        // ==================================================
        // AUTHENTICATION
        // ==================================================

        const user =
            getUser(req);


        if (!user) {

            return res.redirect(
                "/login"
            );

        }


        // ==================================================
        // TYPE
        // ==================================================

        const type =
            req.query?.type ||
            "day";


        // ==================================================
        // DAILY STATISTICS
        // ==================================================

        if (
            type === "day"
        ) {

            const kenyaParts =
                milkService.getKenyaDateParts();


            const selectedDate =
                req.query?.date ||
                kenyaParts.date;


            const data =
                await milkService.getDailyStats(

                    selectedDate,

                    user

                );


            return res.render(
                "milkStats",
                {

                    type:
                        "day",

                    date:
                        selectedDate,

                    month:
                        "",

                    records:
                        Array.isArray(
                            data?.records
                        )
                            ? data.records
                            : [],

                    stats:
                        data?.stats ||
                        {},

                    sales:
                        Array.isArray(
                            data?.sales
                        )
                            ? data.sales
                            : [],

                    farmTotals:
                        Array.isArray(
                            data?.farmTotals
                        )
                            ? data.farmTotals
                            : [],

                    user

                }
            );

        }


        // ==================================================
        // MONTHLY STATISTICS
        // ==================================================

        if (
            type === "month"
        ) {

            const kenyaParts =
                milkService.getKenyaDateParts();


            const selectedMonth =
                req.query?.month ||
                kenyaParts.monthKey;


            const data =
                await milkService.getMonthlyStats(

                    selectedMonth,

                    user

                );


            return res.render(
                "milkStats",
                {

                    type:
                        "month",

                    date:
                        "",

                    month:
                        selectedMonth,

                    records:
                        Array.isArray(
                            data?.records
                        )
                            ? data.records
                            : [],

                    stats:
                        data?.stats ||
                        {},

                    sales:
                        Array.isArray(
                            data?.sales
                        )
                            ? data.sales
                            : [],

                    farmTotals:
                        Array.isArray(
                            data?.farmTotals
                        )
                            ? data.farmTotals
                            : [],

                    user

                }
            );

        }


        // ==================================================
        // INVALID TYPE
        // ==================================================

        return res.status(
            400
        ).render(
            "milkStats",
            {

                type:
                    "",

                date:
                    "",

                month:
                    "",

                records:
                    [],

                stats: {

                    total:
                        0,

                    production:
                        0,

                    consumed:
                        0,

                    sold:
                        0,

                    available:
                        0,

                    price:
                        0,

                    cash:
                        0,

                    revenue:
                        0,

                    locked:
                        false,

                    avg:
                        0

                },

                sales:
                    [],

                farmTotals:
                    [],

                user

            }
        );

    }

    catch (error) {

        return sendError(
            res,
            error,
            "Unable to load milk statistics."
        );

    }

};


