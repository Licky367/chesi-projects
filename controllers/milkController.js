// ==========================================================
// GET SALES PAGE
// ==========================================================
//
// GET /sales
//
// IMPORTANT
// ----------------------------------------------------------
//
// getSalesPageData(user) returns:
//
//     standingOrders
//     manualSales
//     farmTotals
//     currentPrice
//     totalSales
//     totalProduction
//     totalRevenue
//     availableMilk
//
// ALL of these are passed to sales.ejs.
//
// ==========================================================

exports.getSalesPage =
async function(
    req,
    res
) {

    try {

        const user =
            getUser(req);


        // ==================================================
        // AUTHENTICATION
        // ==================================================

        if (!user) {

            return res.redirect(
                "/login"
            );

        }


        // ==================================================
        // PAGE DATA
        // ==================================================

        const data =
            await milkService.getSalesPageData(
                user
            );


        // ==================================================
        // FARM TOTALS
        // ==================================================

        const farmTotals =
            Array.isArray(
                data?.farmTotals
            )
                ? data.farmTotals
                : [];


        // ==================================================
        // SELECTED FARM
        // ==================================================
        //
        // The service calculates farmTotals for all farms
        // belonging to the logged-in user.
        //
        // If the request already contains a farmId, preserve
        // it.
        //
        // Otherwise select the first available farm.
        //
        // ==================================================

        let selectedFarmId =
            req.query?.farmId ||
            "";


        if (
            !selectedFarmId &&
            farmTotals.length
        ) {

            selectedFarmId =
                farmTotals[0].farmId?.toString() ||
                "";

        }


        // ==================================================
        // RENDER
        // ==================================================

        return res.render(
            "sales",
            {

                standingOrders:
                    Array.isArray(
                        data?.standingOrders
                    )
                        ? data.standingOrders
                        : [],

                manualSales:
                    Array.isArray(
                        data?.manualSales
                    )
                        ? data.manualSales
                        : [],

                farmTotals,

                selectedFarmId,

                currentPrice:
                    Number(
                        data?.currentPrice ?? 50
                    ),

                totalSales:
                    Number(
                        data?.totalSales || 0
                    ),

                totalProduction:
                    Number(
                        data?.totalProduction || 0
                    ),

                totalRevenue:
                    Number(
                        data?.totalRevenue || 0
                    ),

                availableMilk:
                    Number(
                        data?.availableMilk || 0
                    ),

                user

            }
        );

    }

    catch (error) {

        return sendError(
            res,
            error,
            "Unable to load sales page."
        );

    }

};


// ==========================================================
// SUBMIT MANUAL SALE
// ==========================================================
//
// POST /sales/manual
//
// Required by service:
//
//     farmId
//     customerName
//     liters
//     user
//
// ==========================================================

exports.submitManualSale =
async function(
    req,
    res
) {

    try {

        const user =
            getUser(req);


        // ==================================================
        // AUTHENTICATION
        // ==================================================

        if (!user) {

            return res.redirect(
                "/login"
            );

        }


        // ==================================================
        // FARM
        // ==================================================

        const farmId =
            req.body?.farmId;


        if (
            farmId === undefined ||
            farmId === null ||
            farmId === ""
        ) {

            throw new Error(
                "A dairy farm must be selected."
            );

        }


        // ==================================================
        // CUSTOMER
        // ==================================================

        const customerName =
            typeof req.body?.customerName === "string"

                ? req.body.customerName.trim()

                : "";


        if (!customerName) {

            throw new Error(
                "Customer name is required."
            );

        }


        // ==================================================
        // LITERS
        // ==================================================

        const rawLiters =
            req.body?.liters;


        if (
            rawLiters === undefined ||
            rawLiters === null ||
            rawLiters === ""
        ) {

            throw new Error(
                "Liters are required."
            );

        }


        const liters =
            Number(
                rawLiters
            );


        if (
            !Number.isFinite(
                liters
            ) ||
            liters <= 0
        ) {

            throw new Error(
                "Liters must be a valid number greater than zero."
            );

        }


        // ==================================================
        // SAVE FARM-SCOPED SALE
        // ==================================================

        await milkService.submitManualSale({

            farmId,

            customerName,

            liters,

            user

        });


        // ==================================================
        // SUCCESS
        // ==================================================

        return res.redirect(
            `/sales?farmId=${encodeURIComponent(farmId)}&success=${encodeURIComponent("Sale recorded successfully.")}`
        );

    }

    catch (error) {

        return sendError(
            res,
            error,
            "Unable to save manual sale."
        );

    }

};


