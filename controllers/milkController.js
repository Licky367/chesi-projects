exports.unlockDay =
async function(
    req,
    res
) {

    try {

        const user =
            getUser(req);


        if (!user) {

            return res.redirect(
                "/login"
            );

        }


        if (
            user.role !== "admin"
        ) {

            return res.status(
                403
            ).send(
                "Only administrators can unlock daily summaries."
            );

        }


        const day =
            req.body?.day;


        if (!day) {

            throw new Error(
                "Day is required."
            );

        }


        await milkService.unlockDay(

            day,

            user

        );


        return res.redirect(
            `/stats?type=day&date=${encodeURIComponent(day)}`
        );

    }

    catch (error) {

        return sendError(
            res,
            error,
            "Unable to unlock daily summary."
        );

    }

};


